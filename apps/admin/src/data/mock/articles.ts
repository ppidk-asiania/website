/** Does an article belong under the given tab? "All" shows everything (112 in
 *  the seed, matching the Figma "Showing 1–10 of 112"); "Drafts" only draft
 *  rows; "Published" holds every non-draft article (mock: the tab counts map
 *  to the seed's published/private rows). */
export function matchesArticleTab(a: ArticleItem, tab: ArticleTab): boolean {
  if (tab === "all") return true;
  if (tab === "drafts") return a.status === "draft";
  return a.status !== "draft";
}
