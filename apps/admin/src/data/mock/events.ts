export type EventStatus = "published" | "private" | "draft";
export type EventTab = "all" | "upcoming" | "past" | "drafts";

export interface EventItem {
  id: string;
  title: string;
  type: string;
  /** ISO event date (start). "Past/upcoming" is decided against today. */
  date: string;
  registrationDeadline?: string;
  location: string;
  /** City + country shown in the Location column (with map-pin icon). */
  city: string;
  country: string;
  /** Name of the admin who last modified the event (under Last Modified). */
  updatedBy: string;
  /** Public slug, e.g. "simposium-2026". */
  url: string;
  description?: string;
  registrationLink?: string;
  /** Event logo — local placeholder art under /events (see public/events). */
  image?: string;
  status: EventStatus;
  createdAt: string;
}

/** ISO date → "11 May 2026". */
export function formatDate(iso: string): string {
  const d = new Date(iso.length === 10 ? `${iso}T00:00:00` : iso);
  if (Number.isNaN(d.getTime())) return iso;
  const MONTHS = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "May",
    "Jun",
    "Jul",
    "Aug",
    "Sep",
    "Oct",
    "Nov",
    "Dec",
  ];
  return `${d.getDate()} ${MONTHS[d.getMonth()]} ${d.getFullYear()}`;
}

function daysFromNow(days: number): string {
  const d = new Date(Date.UTC(2026, 9, 15) + days * 86_400_000);
  return d.toISOString().slice(0, 10);
}

