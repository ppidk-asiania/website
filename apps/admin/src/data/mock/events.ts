/** Whether an event matches a list tab. "All" shows every event including
 *  saved drafts (so they surface in the main list, like Articles); Drafts
 *  shows only drafts; Upcoming/Past bucket the published + private rows by
 *  date. */
export function matchesTab(e: EventItem, tab: EventTab, todayIso: string): boolean {
  if (tab === "all") return true;
  if (tab === "drafts") return e.status === "draft";
  if (e.status === "draft") return false;
  return tab === "upcoming" ? e.date >= todayIso : e.date < todayIso;
}
